const glyphs = new Map();
const order = [];
const CELL = 8;
for (const ch of Object.keys(SRC)) {
  const rows = SRC[ch].split('|');
  let min = 99, max = -1;
  for (const r of rows) for (let i = 0; i < r.length; i++) if (r[i] === '1') { if (i < min) min = i; if (i > max) max = i; }
  const px = [];
  rows.forEach((r, y) => { for (let i = 0; i < r.length; i++) if (r[i] === '1') px.push(i - min, y); });
  glyphs.set(ch, { w: max - min + 1, px, sx: order.length * CELL });
  order.push(ch);
}

const atlases = new Map();
function atlas(color) {
  let a = atlases.get(color);
  if (a) return a;
  a = document.createElement('canvas');
  a.width = order.length * CELL;
  a.height = ROWS;
  const g = a.getContext('2d');
  g.fillStyle = color;
  for (const ch of order) {
    const gl = glyphs.get(ch);
    for (let i = 0; i < gl.px.length; i += 2) g.fillRect(gl.sx + gl.px[i], gl.px[i + 1], 1, 1);
  }
  atlases.set(color, a);
  return a;
}

export const hasGlyph = (ch) => ch === ' ' || glyphs.has(ch);

export function textWidth(str, s = 1) {
  let w = 0;
  for (const ch of str) {
    if (ch === ' ') { w += 3; continue; }
    const g = glyphs.get(ch) || glyphs.get('?');
    w += g.w + 1;
  }
  return Math.max(0, w - 1) * s;
}

export function drawText(ctx, str, x, y, color, s = 1) {
  const a = atlas(color);
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of str) {
    if (ch === ' ') { cx += 3 * s; continue; }
    const g = glyphs.get(ch) || glyphs.get('?');
    ctx.drawImage(a, g.sx, 0, g.w, ROWS, cx, cy, g.w * s, ROWS * s);
    cx += (g.w + 1) * s;
  }
  return cx;
}

export function wrapText(str, maxW, s = 1) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t, s) > maxW && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
}

export function fitText(str, maxW, s = 1) {
  if (textWidth(str, s) <= maxW) return str;
  let t = str;
  while (t.length > 1 && textWidth(t + '…', s) > maxW) t = t.slice(0, -1);
  return t.trimEnd() + '…';
}

